-- =====================================================================
-- Skema database Dashboard Kehutanan (PostgreSQL / Supabase)
--
-- Satu database Postgres, tiga schema, mengikuti alur Data-level EAI:
--   1. kehutanan_staging   : hasil EXTRACT, isi masih teks asli dari file
--   2. kehutanan_master    : hasil TRANSFORM + LOAD, data bersih & seragam (sumber kebenaran)
--   3. kehutanan_dashboard : REPLIKA dari master, satu-satunya schema yang dibaca website
--
-- Schema di luar `public` tidak diekspos oleh Data API (PostgREST) Supabase, jadi data tidak terbuka lewat anon key.
-- Jalankan ulang file ini = reset total ketiga schema (tabel milik Laravel di `public` tidak disentuh).
-- Cara menjalankan: python etl/init_db.py
-- =====================================================================

DROP SCHEMA IF EXISTS kehutanan_dashboard CASCADE;
DROP SCHEMA IF EXISTS kehutanan_master CASCADE;
DROP SCHEMA IF EXISTS kehutanan_staging CASCADE;
CREATE SCHEMA kehutanan_staging;
CREATE SCHEMA kehutanan_master;
CREATE SCHEMA kehutanan_dashboard;

-- ---------------------------------------------------------------------
-- 1. STAGING: semua kolom nilai bertipe teks, persis seperti di sumber
-- ---------------------------------------------------------------------
SET search_path TO kehutanan_staging;

CREATE TABLE stg_d1_tutupan_kelas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sumber_file  VARCHAR(120) NOT NULL,
    baris_ke     SMALLINT     NOT NULL,
    kelompok_raw VARCHAR(40),
    no_raw       VARCHAR(10),
    kelas_raw    VARCHAR(120),
    tahun_data   SMALLINT     NOT NULL,
    kawasan_raw  VARCHAR(40),
    apl_raw      VARCHAR(40),
    total_raw    VARCHAR(40),
    extracted_at TIMESTAMP     NOT NULL
);

CREATE TABLE stg_d2_tutupan_lahan (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sumber_file       VARCHAR(120) NOT NULL,
    blok              VARCHAR(20)  NOT NULL,
    baris_ke          SMALLINT     NOT NULL,
    provinsi_raw      VARCHAR(120),
    tahun_data        SMALLINT     NOT NULL,
    hutan_raw         VARCHAR(40),
    hutan_pct_raw     VARCHAR(20),
    non_hutan_raw     VARCHAR(40),
    non_hutan_pct_raw VARCHAR(20),
    jumlah_raw        VARCHAR(40),
    extracted_at      TIMESTAMP     NOT NULL
);

CREATE TABLE stg_d3_karhutla (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sumber_file      VARCHAR(120) NOT NULL,
    baris_ke         SMALLINT     NOT NULL,
    kode_wilayah_raw VARCHAR(10),
    provinsi_raw     VARCHAR(120),
    tahun_data       SMALLINT     NOT NULL,
    luas_raw         VARCHAR(40),
    extracted_at     TIMESTAMP     NOT NULL
);

CREATE TABLE stg_d4_produksi_kayu (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sumber_file     VARCHAR(120) NOT NULL,
    datacontent_key VARCHAR(40)  NOT NULL,
    vervar_val      VARCHAR(10),
    provinsi_raw    VARCHAR(120),
    tahun_data      SMALLINT     NOT NULL,
    nilai_raw       VARCHAR(40),
    extracted_at    TIMESTAMP     NOT NULL
);

CREATE TABLE stg_d5_deforestasi (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sumber_file       VARCHAR(120) NOT NULL,
    baris_ke          SMALLINT     NOT NULL,
    provinsi_raw      VARCHAR(120),
    periode_raw       VARCHAR(20),
    dalam_kawasan_raw VARCHAR(40),
    luar_kawasan_raw  VARCHAR(40),
    total_raw         VARCHAR(40),
    extracted_at      TIMESTAMP     NOT NULL
);

-- ---------------------------------------------------------------------
-- 2. MASTER: data bersih, satuan seragam, kunci = kode provinsi BPS
-- ---------------------------------------------------------------------
SET search_path TO kehutanan_master;

CREATE TABLE ref_provinsi (
    kode_bps   CHAR(2)     PRIMARY KEY,
    nama       VARCHAR(60) NOT NULL,
    wilayah    VARCHAR(30) NOT NULL,
    updated_at TIMESTAMP    NOT NULL
);

-- D1 bersifat nasional (tanpa provinsi): satu baris = satu kelas penutupan lahan per tahun
CREATE TABLE fakta_tutupan_kelas (
    kode_kelas  SMALLINT     NOT NULL,  -- nomor kelas di tabel BPS (1-21)
    tahun       SMALLINT    NOT NULL,
    kelas       VARCHAR(60) NOT NULL,
    kelompok    VARCHAR(10) NOT NULL,  -- hutan / non_hutan
    jenis_hutan VARCHAR(10),           -- primer / sekunder / tanaman (khusus kelas hutan)
    kawasan_ha  DECIMAL(14,2),         -- di dalam kawasan hutan
    apl_ha      DECIMAL(14,2),         -- di luar kawasan (Areal Penggunaan Lain)
    total_ha    DECIMAL(14,2),
    updated_at  TIMESTAMP    NOT NULL,
    PRIMARY KEY (kode_kelas, tahun)
);

CREATE TABLE fakta_tutupan_lahan (
    kode_bps     CHAR(2)  NOT NULL,
    tahun        SMALLINT NOT NULL,
    hutan_ha     DECIMAL(14,2),
    non_hutan_ha DECIMAL(14,2),
    total_ha     DECIMAL(14,2),
    persen_hutan DECIMAL(5,2),
    catatan      VARCHAR(200),
    updated_at   TIMESTAMP NOT NULL,
    PRIMARY KEY (kode_bps, tahun)
);

CREATE TABLE fakta_karhutla (
    kode_bps   CHAR(2)  NOT NULL,
    tahun      SMALLINT NOT NULL,
    luas_ha    DECIMAL(14,2),
    updated_at TIMESTAMP NOT NULL,
    PRIMARY KEY (kode_bps, tahun)
);

CREATE TABLE fakta_produksi_kayu (
    kode_bps    CHAR(2)  NOT NULL,
    tahun       SMALLINT NOT NULL,
    produksi_m3 DECIMAL(16,2),
    updated_at  TIMESTAMP NOT NULL,
    PRIMARY KEY (kode_bps, tahun)
);

CREATE TABLE fakta_deforestasi (
    kode_bps         CHAR(2)    NOT NULL,
    periode          VARCHAR(9) NOT NULL,
    tahun_awal       SMALLINT   NOT NULL,
    tahun_akhir      SMALLINT   NOT NULL,
    dalam_kawasan_ha DECIMAL(14,2),
    luar_kawasan_ha  DECIMAL(14,2),
    total_ha         DECIMAL(14,2),
    updated_at       TIMESTAMP   NOT NULL,
    PRIMARY KEY (kode_bps, periode)
);

-- Catatan setiap tahap ETL & hasil cek kualitas
CREATE TABLE etl_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(20) NOT NULL,
    tahap         VARCHAR(20) NOT NULL,
    dataset       VARCHAR(10) NOT NULL,
    baris_masuk   INT,
    baris_dimuat  INT,
    baris_dibuang INT,
    status        VARCHAR(10) NOT NULL,
    pesan         TEXT,
    waktu         TIMESTAMP    NOT NULL
);

-- Catatan replikasi (lihat etl/replicate.py). Ditulis di master agar ikut tersalin ke replika.
CREATE TABLE replication_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mode             VARCHAR(20) NOT NULL,  -- script
    tabel            VARCHAR(40) NOT NULL,
    baris_master     INT NOT NULL,
    baris_replika    INT,
    baris_disisipkan INT,                   -- jumlah baris yang disisipkan script replikasi
    baris_diperbarui INT,
    baris_dihapus    INT,
    checksum_master  BIGINT,
    checksum_replika BIGINT,
    status           VARCHAR(10) NOT NULL,
    waktu            TIMESTAMP NOT NULL
);

-- Catatan sinkronisasi file sumber (D1-D5) -> master, satu baris per data per putaran
CREATE TABLE sync_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset       VARCHAR(10) NOT NULL,
    baris_dicek   INT NOT NULL,
    baris_baru    INT NOT NULL,
    baris_berubah INT NOT NULL,
    baris_dihapus INT NOT NULL DEFAULT 0,
    baris_sama    INT NOT NULL,
    detail        TEXT,
    waktu         TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- 3. DASHBOARD (replika): struktur disalin persis dari master
-- ---------------------------------------------------------------------
SET search_path TO kehutanan_dashboard;

CREATE TABLE ref_provinsi        (LIKE kehutanan_master.ref_provinsi        INCLUDING ALL);
CREATE TABLE fakta_tutupan_kelas (LIKE kehutanan_master.fakta_tutupan_kelas INCLUDING ALL);
CREATE TABLE fakta_tutupan_lahan (LIKE kehutanan_master.fakta_tutupan_lahan INCLUDING ALL);
CREATE TABLE fakta_karhutla      (LIKE kehutanan_master.fakta_karhutla      INCLUDING ALL);
CREATE TABLE fakta_produksi_kayu (LIKE kehutanan_master.fakta_produksi_kayu INCLUDING ALL);
CREATE TABLE fakta_deforestasi   (LIKE kehutanan_master.fakta_deforestasi   INCLUDING ALL);
CREATE TABLE etl_log             (LIKE kehutanan_master.etl_log             INCLUDING ALL);
CREATE TABLE sync_log            (LIKE kehutanan_master.sync_log            INCLUDING ALL);
CREATE TABLE replication_log     (LIKE kehutanan_master.replication_log     INCLUDING ALL);

SET search_path TO public;
